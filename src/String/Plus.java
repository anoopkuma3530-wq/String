package String;

public class Plus {
    public static void main(String[] args) {
        String s1="Anoop ";
        String s2="Kumar ";
        String s3="Prajapati";
        System.out.println(s1+s2+s3);

        System.out.println("anoop"+476+25);
        System.out.println(476+"kumar");
        System.out.println(10+"anoop"+20);
        System.out.println(10+20+"anoop");
        System.out.println('A'+100+"anoop"); //A=65
    }
}
